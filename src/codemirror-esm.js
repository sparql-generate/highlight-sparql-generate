'use strict';
/**
 * `dist/codemirror.mjs`: the CodeMirror 6 language as ONE ES module, for
 * pages that load modules without a bundler (the playground, an import map).
 *
 * It is `src/codemirror.js` with the lexicon inlined and the two CommonJS
 * seams turned into imports — a textual transformation, checked: each
 * replaced snippet must be found exactly once, so an edit of the source that
 * breaks a seam fails `npm run generate` instead of shipping a broken file.
 *
 * The module imports only `@codemirror/legacy-modes/mode/sparql` and
 * `@lezer/highlight`, which every CodeMirror 6 setup already has.
 */
const fs = require('fs');
const path = require('path');
const L = require('./lexicon');

function replaceOnce(text, from, to) {
    const n = text.split(from).length - 1;
    if (n !== 1) {
        throw new Error(`codemirror-esm: expected one ${JSON.stringify(from)} in src/codemirror.js, found ${n}`);
    }
    return text.replace(from, to);
}

function esmText() {
    let src = fs.readFileSync(path.join(__dirname, 'codemirror.js'), 'utf8');
    src = replaceOnce(src, "'use strict';\n", '');
    src = replaceOnce(src, "const L = require('./lexicon');",
        '// The lexicon (src/lexicon.js), inlined.\nconst L = ' +
        JSON.stringify({ P: L.P }, null, 4) + ';');
    src = replaceOnce(src,
        "options.sparql ||\n        require('@codemirror/legacy-modes/mode/sparql').sparql;",
        'options.sparql || baseSparql;');
    src = replaceOnce(src, 'module.exports = { build, tokenTable, TOKEN };',
        '/** The language, ready for `StreamLanguage.define`. */\n' +
        'const sparqlGenerate = build({ tags });\n\n' +
        'export { build, tokenTable, TOKEN, sparqlGenerate };\n' +
        'export default sparqlGenerate;');
    const head = [
        '// GENERATED by `npm run generate` from src/codemirror.js and',
        '// src/lexicon.js of highlight-sparql-generate. Do not edit.',
        "import { sparql as baseSparql } from '@codemirror/legacy-modes/mode/sparql';",
        "import { tags } from '@lezer/highlight';",
        '',
    ].join('\n');
    return head + src;
}

module.exports = { esmText };
