'use strict';
/**
 * The lexicon, as a Python module for the Pygments lexer.
 *
 * Pygments cannot read JavaScript, and a second hand-written copy of the word
 * lists would drift. So `npm run generate` writes
 * `pygments-sparql-generate/pygments_sparql_generate/_lexicon.py` from
 * `src/lexicon.js`; `npm test` and `pytest` fail if the file in the tree is
 * not the output of this function.
 *
 * JSON string literals are valid Python string literals, escapes included.
 */
const L = require('./lexicon');

function pythonLexicon() {
    const lines = [
        '"""The SPARQL-Generate lexicon, for the Pygments lexer.',
        '',
        'GENERATED by `npm run generate` from src/lexicon.js of',
        'highlight-sparql-generate. Do not edit: edit src/lexicon.js and regenerate.',
        '"""',
        '',
    ];
    const lists = ['SPARQL_KEYWORDS', 'SPARQL_BUILTINS', 'GENERATE_KEYWORDS',
        'GENERATE_BUILTINS', 'REUSED_KEYWORDS', 'LIBRARY_PREFIXES'];
    for (const name of lists) {
        lines.push(`${name} = [`);
        for (const w of L[name]) lines.push(`    ${JSON.stringify(w)},`);
        lines.push(']', '');
    }
    lines.push('# Final regular-expression sources (Python `re` syntax).');
    lines.push('P = {');
    for (const [k, v] of Object.entries(L.P)) {
        lines.push(`    ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
    }
    lines.push('}', '');
    lines.push('ROLES = {');
    for (const [k, v] of Object.entries(L.ROLES)) {
        lines.push(`    ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
    }
    lines.push('}', '');
    return lines.join('\n');
}

module.exports = { pythonLexicon };
